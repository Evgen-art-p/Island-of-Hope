def skazat(s=""):
    print(s, flush=True)


def eto_ostrov() -> bool:
    return (KOREN / "ostrov_puls.py").is_file() or OSTROV_MD.is_file()


def pravit_birzhu(suho: bool) -> bool:
    if not BIRZHA_MD.exists():
        skazat("  БИРЖА.md рядом нет — пропускаю")
        return True
    t = BIRZHA_MD.read_text(encoding="utf-8")
    if MARKER in t:
        skazat("  БИРЖА.md: уже обновлён")
        return True
    a = t.find("## Состояние прямо сейчас")
    b = t.find("## 1. Что такое Биржа")
    if a < 0 or b < 0 or b <= a:
        skazat("  x БИРЖА.md: не нашёл голову документа — не трогаю")
        return False
    skazat(f"  БИРЖА.md: снесу устаревшую голову ({b - a} знаков), "
           f"впишу нынешнее состояние и раздел о сделанном")
    if not suho:
        shutil.copy2(BIRZHA_MD, BIRZHA_MD.with_suffix(".md" + BAK))
        BIRZHA_MD.write_text(t[:a] + GOLOVA + t[b:], encoding="utf-8")
    return True


def pravit_letopis(suho: bool) -> bool:
    if not LETOPIS.exists():
        skazat("  ЛЕТОПИСИ рядом нет — пропускаю")
        return True
    t = LETOPIS.read_text(encoding="utf-8")
    if MARKER in t:
        skazat("  ЛЕТОПИСЬ: запись уже есть")
        return True
    zapis = f'''

---

## 08–13.08 — неделя Биржи {MARKER}

Трейдер впервые дошёл до конца: строка, делавшая имя местным, роняла
каждый вызов модели молча — за всё время он не отработал ни разу.

Дальше снимали с него куклу. Из мозгов ушла станция, выданная местом;
ушёл «Закон входа, железно, без исключений»; ушёл выданный темперамент
в разговоре. Три места входа легли в знания без хозяина, а выбор стал
МЕТКОЙ жителя — объявляется словом и носится с человеком везде.

Работу отделили от личности: место стало постом с бланком и трудовой
историей, приём и увольнение — на Странице Работы, личное при
увольнении уезжает с человеком.

Вакансию стала давать локация. Цех стал картриджем: свой стол, Совет по
сканеру вместо списка, размножение и вынимание на странице.

Архив перестал быть складом и стал доступом ко всем памятям города.

Заведён остров: Биржа, Маяк и свои локации, без жителей; люди возятся
архивом.

Убрано 69 файлов и 3 МБ отработавшего.
'''
