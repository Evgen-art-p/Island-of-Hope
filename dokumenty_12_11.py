def dopisat(p: Path, tekst: str, imya: str):
    if not p.is_file():
        print(f"· {imya}: файла нет — пропускаю")
        return
    t = p.read_bytes().decode("utf-8")
    bom = t.startswith("\ufeff")
    if bom:
        t = t[1:]
    crlf = "\r\n" in t
    t = t.replace("\r\n", "\n")
    if f"<!-- {M} -->" in t:
        print(f"· {imya}: уже дописан")
        return
    bak = p.with_name(p.name + ".bak_dok1211")
    if not bak.exists():
        shutil.copy2(p, bak)
    nov = t.rstrip("\n") + tekst
    if crlf:
        nov = nov.replace("\n", "\r\n")
    p.write_bytes((("\ufeff" + nov) if bom else nov).encode("utf-8"))
    print(f"✓ {imya}: раздел дописан")


