# -*- coding: utf-8 -*-
# OSTROV_PULS_V1 — остров начинает говорить
"""
Простой скрипт: остров реально шлёт пульс на материк.

Причал (prichal.py) у тебя уже лежит в Маяк/ — он только УМЕЕТ
слать и принимать. Этот файл — тот, кто его реально ЗОВЁТ со
стороны острова.

Настрой три вещи ниже (МАТЕРИК, ID, ИМЯ) и запусти:
    python ostrov_puls.py

Один раз — просто открытка и выход. Если хочешь, чтобы остров
стучался сам, регулярно, без тебя — запусти вечный режим:
    python ostrov_puls.py --вечно
(будет слать каждые 5 минут, пока не остановишь Ctrl+C)
"""
import asyncio
import sys
from pathlib import Path

# Причал лежит в Маяк/ рядом с этим файлом (та же копия, что и на материке)
sys.path.insert(0, str(Path(__file__).resolve().parent / "Маяк"))
from prichal import otpravit

# ═══════════════════════════════════════════════════
# НАСТРОЙ ЭТО ПОД СЕБЯ — три строки ниже
# ═══════════════════════════════════════════════════
МАТЕРИК = "http://localhost:8080"     # адрес Грондхейма (материка)
ID_ОСТРОВА = "island-of-hope"         # короткое имя, латиница/цифры/-_
ИМЯ_ОСТРОВА = "Остров_Надежды"        # как называть по-человечески
ИНТЕРВАЛ_МИНУТ = 5                    # только для режима --вечно
# ═══════════════════════════════════════════════════


def нынешние_числа() -> dict:
    """Тут остров сам решает, что рассказать о себе материку.
    Сейчас — заглушка. Замени на настоящие цифры острова, когда
    появятся (сколько жителей, что происходит и т.п.)."""
    return {
        "жителей": 0,
        "настроение": "спокойно",
    }


async def один_пульс() -> dict:
    """Шлёт ровно одну открытку и возвращает, что ответил материк."""
    print(f"── стучусь в {МАТЕРИК} ...")
    рез = await otpravit(
        kuda=МАТЕРИК,
        id=ID_ОСТРОВА,
        imya=ИМЯ_ОСТРОВА,
        rod="остров",
        chisla=нынешние_числа(),
        versia="v1",
    )
    if рез.get("ok"):
        print(f"✓ пульс принят, id={рез.get('id','')}")
    else:
        print(f"✗ не принят: {рез.get('причина','')}")
    return рез


async def вечно():
    """Стучится сам, по расписанию, пока не остановишь."""
    while True:
        await один_пульс()
        await asyncio.sleep(ИНТЕРВАЛ_МИНУТ * 60)


if __name__ == "__main__":
    if "--вечно" in sys.argv:
        print(f"остров будет стучаться каждые {ИНТЕРВАЛ_МИНУТ} мин. Ctrl+C — остановить.")
        asyncio.run(вечно())
    else:
        asyncio.run(один_пульс())
